import { chmodSync, writeFileSync } from "node:fs";
import path from "node:path";
import { spawn } from "node:child_process";
import { platform as osPlatform } from "node:os";

/** Sidecar list of relative .osz paths for the fixed import scripts to open. */
export const IMPORT_QUEUE_FILENAME = ".roxysu-import-queue.txt";

/** Pause between opening archives so lazer is not flooded (server + bash). */
export const OPEN_BETWEEN_MS = 250;

export type ImportScriptPaths = {
  /** POSIX shell script (Linux / macOS). */
  sh: string;
  /** Windows batch script. */
  bat: string;
  /** Pending archive list read by the scripts. */
  queue: string;
};

/**
 * Write companion scripts next to downloaded .osz archives so the user can
 * import them into osu!lazer later:
 * - `import-into-osu.sh` — prefers `osu!` / `osu` on PATH, else `xdg-open` / `open`
 * - `import-into-osu.bat` — `start "" file.osz` (Windows file association)
 * - `.roxysu-import-queue.txt` — one relative path per line (scripts loop this)
 *
 * Scripts are fixed-size drivers; only the queue file grows with the batch.
 */
export function writeOsuImportScripts(
  downloadDir: string,
  oszPaths: string[],
): ImportScriptPaths {
  const shPath = path.join(downloadDir, "import-into-osu.sh");
  const batPath = path.join(downloadDir, "import-into-osu.bat");
  const queuePath = path.join(downloadDir, IMPORT_QUEUE_FILENAME);

  const relativeOrAbs = (filePath: string): string => {
    const rel = path.relative(downloadDir, filePath);
    if (!rel.startsWith("..") && !path.isAbsolute(rel)) return rel;
    return filePath;
  };

  const queueLines = oszPaths.map((filePath) =>
    relativeOrAbs(filePath).replace(/\\/g, "/"),
  );
  writeFileSync(queuePath, `${queueLines.join("\n")}${queueLines.length ? "\n" : ""}`, {
    encoding: "utf8",
  });

  const sleepSec = (OPEN_BETWEEN_MS / 1000).toFixed(2);
  // cmd `timeout` only accepts whole seconds; keep 1s on Windows.
  const batTimeoutSec = Math.max(1, Math.ceil(OPEN_BETWEEN_MS / 1000));

  const sh = `#!/usr/bin/env bash
# Generated by Roxysu — open downloaded .osz archives in osu!lazer.
# Reads paths from ${IMPORT_QUEUE_FILENAME} (do not list maps in this script).
set -euo pipefail
DIR="$(cd "$(dirname "\${BASH_SOURCE[0]}")" && pwd)"
cd "$DIR"
QUEUE="${IMPORT_QUEUE_FILENAME}"

if [[ ! -f "$QUEUE" ]]; then
  echo "No import queue ($QUEUE). Download maps in Roxysu first."
  exit 1
fi

open_one() {
  local f=$1
  if command -v "osu!" >/dev/null 2>&1; then
    "osu!" "$f" >/dev/null 2>&1 &
  elif command -v osu >/dev/null 2>&1; then
    osu "$f" >/dev/null 2>&1 &
  elif command -v osu-lazer >/dev/null 2>&1; then
    osu-lazer "$f" >/dev/null 2>&1 &
  elif [[ "$(uname -s)" == Darwin ]]; then
    open "$f"
  else
    xdg-open "$f" >/dev/null 2>&1 || open "$f"
  fi
  sleep ${sleepSec}
}

count=0
while IFS= read -r f || [[ -n "\${f:-}" ]]; do
  [[ -z "\${f:-}" ]] && continue
  count=$((count + 1))
done < "$QUEUE"

echo "Importing $count beatmap archive(s) into osu!…"
while IFS= read -r f || [[ -n "\${f:-}" ]]; do
  [[ -z "\${f:-}" ]] && continue
  open_one "$f"
done < "$QUEUE"
echo "Done. Check osu!lazer for import prompts."
`;

  writeFileSync(shPath, sh, { encoding: "utf8" });
  try {
    chmodSync(shPath, 0o755);
  } catch {
    // Non-POSIX filesystems may reject chmod; script is still usable via `bash`.
  }

  const bat = `@echo off
REM Generated by Roxysu — open downloaded .osz archives in osu!lazer.
REM Reads paths from ${IMPORT_QUEUE_FILENAME} (do not list maps in this script).
setlocal EnableExtensions
set "DIR=%~dp0"
cd /d "%DIR%"
set "QUEUE=${IMPORT_QUEUE_FILENAME}"
if not exist "%QUEUE%" (
  echo No import queue (%QUEUE%). Download maps in Roxysu first.
  exit /b 1
)
echo Importing beatmap archives from %QUEUE% into osu!...
for /f "usebackq delims=" %%f in ("%QUEUE%") do (
  start "" "%%f"
  timeout /t ${batTimeoutSec} /nobreak >nul
)
echo Done. Check osu!lazer for import prompts.
endlocal
`;

  writeFileSync(batPath, bat.replace(/\n/g, "\r\n"), { encoding: "utf8" });

  return { sh: shPath, bat: batPath, queue: queuePath };
}

function sleep(ms: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

function spawnDetached(command: string, args: string[]): void {
  const child = spawn(command, args, {
    detached: true,
    stdio: "ignore",
    windowsHide: true,
  });
  child.unref();
}

/**
 * Open one .osz with the OS default / osu! handler.
 * Linux: `osu!` / `osu` / `osu-lazer` if on PATH, else `xdg-open`.
 * macOS: `open`.
 * Windows: `cmd /c start "" path`.
 */
export async function openOszWithOsu(
  filePath: string,
  platform: NodeJS.Platform = osPlatform() as NodeJS.Platform,
): Promise<void> {
  if (platform === "win32") {
    spawnDetached("cmd", ["/c", "start", "", filePath]);
    return;
  }
  if (platform === "darwin") {
    spawnDetached("open", [filePath]);
    return;
  }

  // Linux and other POSIX: try lazer binaries, then xdg-open.
  const candidates = ["osu!", "osu", "osu-lazer"];
  for (const bin of candidates) {
    try {
      await new Promise<void>((resolve, reject) => {
        const child = spawn(bin, [filePath], {
          detached: true,
          stdio: "ignore",
        });
        child.on("error", reject);
        child.unref();
        // If spawn succeeds without immediate error, assume it worked.
        setTimeout(() => resolve(), 50);
      });
      return;
    } catch {
      // try next
    }
  }
  spawnDetached("xdg-open", [filePath]);
}

export type OpenOszBatchResult = {
  opened: number;
  failed: number;
  openedPaths: string[];
  errors: Array<{ path: string; error: string }>;
  platform: string;
};

/** Open many archives with a short delay so lazer is not flooded. */
export async function openOszFilesInOsu(
  filePaths: string[],
  opts?: {
    delayMs?: number;
    shouldStop?: () => boolean;
    platform?: NodeJS.Platform;
  },
): Promise<OpenOszBatchResult> {
  const delayMs = opts?.delayMs ?? OPEN_BETWEEN_MS;
  const platform = opts?.platform ?? (osPlatform() as NodeJS.Platform);
  let opened = 0;
  let failed = 0;
  const openedPaths: string[] = [];
  const errors: Array<{ path: string; error: string }> = [];

  for (const filePath of filePaths) {
    if (opts?.shouldStop?.()) break;
    try {
      await openOszWithOsu(filePath, platform);
      opened += 1;
      openedPaths.push(filePath);
    } catch (err) {
      failed += 1;
      errors.push({
        path: filePath,
        error: err instanceof Error ? err.message : String(err),
      });
    }
    if (delayMs > 0) await sleep(delayMs);
  }

  return {
    opened,
    failed,
    openedPaths,
    errors: errors.slice(0, 8),
    platform,
  };
}
